def ensure_square_bracketed_tables(sql_query: str) -> str:
    """
    Auto-fixes T-SQL queries generated by LLMs to ensure all SQL Server table names
    (especially those containing spaces or special characters like 'dbo.Audit Staffing format')
    are safely enclosed in [...] square brackets to prevent T-SQL syntax error 102.
    """
    if not sql_query or not isinstance(sql_query, str):
        return sql_query

    def fix_table_ref(match):
        prefix = match.group(1)       # FROM, JOIN, INTO, UPDATE
        schema = match.group(2) or "" # dbo. or empty
        tbl = match.group(3).strip()  # Table name

        if not (tbl.startswith('[') and tbl.endswith(']')):
            clean_tbl = tbl.replace('[', '').replace(']', '')
            tbl_bracketed = f"[{clean_tbl}]"
        else:
            tbl_bracketed = tbl

        schema_str = schema if schema else ""
        return f"{prefix} {schema_str}{tbl_bracketed}"

    pattern = r"\b(FROM|JOIN|INTO|UPDATE)\s+(dbo\.)?([a-zA-Z0-9_\[\]\s\(\)\-\.]+?)(?=\s+AS\b|\s+ON\b|\s+WHERE\b|\s+GROUP\b|\s+ORDER\b|\s+INNER\b|\s+LEFT\b|\s+RIGHT\b|\s*;|\s*$)"
    return re.sub(pattern, fix_table_ref, sql_query, flags=re.IGNORECASE)

